#!/usr/bin/env python3
"""The inter-event gap distribution of a transcript corpus, and what the v3 tau fit says.

    scripts/measure_gap_distribution.py                      # ~/.claude/projects + real-sessions
    scripts/measure_gap_distribution.py --root DIR           # another Claude Code store
    scripts/measure_gap_distribution.py --extra DIR          # a tree of Codex/Gemini/Cline/
                                                             #   opencode/Aider transcripts
    scripts/measure_gap_distribution.py --synthetic spec/fixtures/boundaries
    make measure-gaps                                        # all of the above, read-only

Prints, per corpus:
  * the gap histogram on log10 seconds in 0.1-decade bins (text bars);
  * the two-component Gaussian-mixture fit on log gaps (scripts/measure_boundaries.fit_tau
    — the same EM the Swift `ThresholdFitter` reproduces), its two modes, the valley where
    the weighted densities cross, and whether the pool is bimodal by the v3 rule;
  * the fraction of gaps above the valley;
  * the session count at the fitted tau against the count at the 900 s fallback;
  * the presence-to-presence intervals that fell during autonomy (> tauAutonomousSec),
    which is the measurement `tauReturnSplitSec` (7200 s) is waiting for;
  * the local hour of every autonomous record and of every idle-gap start, which is the
    measurement the 04:00 `day_boundary` hour is waiting for.

Everything under `--synthetic` is labelled SYNTHETIC in the output: those transcripts were
generated by scripts/gen_boundary_fixtures.py to exercise the rules and say nothing about
how people work. Standard library only, like the reference it imports.
"""

